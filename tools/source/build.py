"""Builds ../../SiteCore.html from src.html + translations (tr.json) + embedded PDF font (fonts.js).
Run from this folder:  python keys.py > nul && python build.py
  - src.html : app source (edit this)
  - tr.json  : {"English key": ["Lao", "Thai"]}; keys.py lists every key used in src.html
  - fonts.js : Latin + Lao + Thai PDF font, generated by mkfont.py
"""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__)); os.chdir(HERE)
src = open('src.html', encoding='utf-8').read()
keys = json.load(open('keys.json', encoding='utf-8'))
tr = {k: v for k, v in json.load(open('tr.json', encoding='utf-8')).items() if v[0]}
print('missing translations:', [k for k in keys if k not in tr])
print('unused translations:', [k for k in tr if k not in keys])
i18n = 'const I18N = ' + json.dumps({'lo': {k: v[0] for k, v in tr.items()}, 'th': {k: v[1] for k, v in tr.items()}}, ensure_ascii=False, separators=(',', ':')) + ';'
out = src.replace('/*__FONTS__*/', open('fonts.js', encoding='utf-8').read()).replace('/*__I18N__*/', i18n)
open(os.path.join(HERE, '..', '..', 'SiteCore.html'), 'w', encoding='utf-8').write(out)
open('app.js', 'w', encoding='utf-8').write('\n'.join(re.findall(r"<script>\n(.*?)</script>", out, re.S)))  # for: node --check app.js
print('SiteCore.html written,', len(out.encode('utf-8')), 'bytes')
